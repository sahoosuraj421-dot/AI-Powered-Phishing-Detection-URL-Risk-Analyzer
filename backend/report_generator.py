"""
report_generator.py – PDF & CSV incident report generation.
"""
from __future__ import annotations

import csv
import io
import json
from datetime import datetime, timezone
from typing import Any


# ─── CSV export ───────────────────────────────────────────────────────────────
def generate_csv(rows: list[dict]) -> bytes:
    """Generate a CSV byte-string from a list of scan-log dicts."""
    out = io.StringIO()
    if not rows:
        out.write("No data\n")
        return out.getvalue().encode()

    fields = ["id", "url", "risk_score", "status", "vt_positives", "vt_total",
              "whois_age_days", "brand_match", "timestamp"]
    writer = csv.DictWriter(out, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()
    for r in rows:
        writer.writerow(r)
    return out.getvalue().encode()


# ─── PDF export ───────────────────────────────────────────────────────────────
def _clean(val: Any) -> str:
    """Encode text safely for core Latin-1 PDF fonts."""
    if val is None:
        return ""
    text = str(val)
    # Replace non-latin1 characters with '?' to prevent FPDFUnicodeEncodingException
    return text.encode("latin-1", "replace").decode("latin-1")


def generate_pdf(rows: list[dict], title: str = "Phishing Scan Report") -> bytes:
    """Generate a PDF report using fpdf2. Falls back to plain text if unavailable or on error."""
    try:
        from fpdf import FPDF
    except ImportError:
        return _fallback_text(rows, title)

    try:
        pdf = FPDF()
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()

        clean_title = _clean(title)

        # ── Header ──
        pdf.set_font("Helvetica", "B", 18)
        pdf.set_text_color(30, 30, 80)
        pdf.cell(0, 12, clean_title, align="C")
        pdf.ln(12)
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(100, 100, 100)
        ts_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        pdf.cell(0, 6, f"Generated: {ts_str}  |  Total records: {len(rows)}", align="C")
        pdf.ln(8)
        pdf.set_draw_color(180, 180, 200)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(4)

        if not rows:
            pdf.set_font("Helvetica", "", 11)
            pdf.cell(0, 8, "No scan records found.")
            pdf.ln(8)
            return bytes(pdf.output())

        # ── Summary stats ──
        total    = len(rows)
        phishing = sum(1 for r in rows if r.get("status") == "Phishing")
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(30, 30, 80)
        pdf.cell(0, 8, "Executive Summary")
        pdf.ln(8)
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(40, 40, 40)
        pdf.cell(0, 6, f"  Total URLs Scanned : {total}")
        pdf.ln(6)
        pct = (phishing * 100 // total) if total else 0
        pdf.cell(0, 6, f"  Phishing Detected  : {phishing} ({pct}%)")
        pdf.ln(6)
        pdf.cell(0, 6, f"  Legitimate         : {total - phishing}")
        pdf.ln(8)

        # ── Table ──
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_fill_color(220, 225, 245)
        pdf.set_text_color(30, 30, 80)
        col_w = [80, 16, 24, 18, 18, 34]
        headers = ["URL", "Score", "Verdict", "VT Det.", "Age(d)", "Timestamp"]
        for w, h in zip(col_w, headers):
            pdf.cell(w, 7, h, border=1, fill=True, align="C")
        pdf.ln(7)

        pdf.set_font("Helvetica", "", 8)
        for i, r in enumerate(rows):
            fill = i % 2 == 0
            pdf.set_fill_color(245, 247, 255) if fill else pdf.set_fill_color(255, 255, 255)
            status = r.get("status", "")
            pdf.set_text_color(180, 30, 30) if status == "Phishing" else pdf.set_text_color(30, 120, 60)
            raw_url = str(r.get("url", ""))
            url_trunc = _clean(raw_url[:55] + ("..." if len(raw_url) > 55 else ""))
            vt = _clean(f"{r.get('vt_positives', '-')}/{r.get('vt_total', '-')}")
            age = _clean(str(r.get("whois_age_days", "-")))
            ts = _clean(str(r.get("timestamp", ""))[:19])
            cells = [url_trunc, _clean(r.get("risk_score", "")), _clean(status), vt, age, ts]
            for w, c in zip(col_w, cells):
                pdf.cell(w, 6, c, border=1, fill=fill)
            pdf.ln(6)
            pdf.set_text_color(40, 40, 40)

        pdf.ln(6)
        pdf.set_font("Helvetica", "I", 8)
        pdf.set_text_color(150, 150, 150)
        pdf.cell(0, 5, "Report generated by Tripwire Phishing Detector", align="C")
        pdf.ln(5)

        return bytes(pdf.output())
    except Exception:
        # Failsafe fallback to clean text format
        return _fallback_text(rows, title)


def _fallback_text(rows: list[dict], title: str) -> bytes:
    lines = [title, "=" * len(title), ""]
    for r in rows:
        lines.append(f"[{r.get('timestamp', '')}] {r.get('url', '')} | {r.get('status', '')} | Score: {r.get('risk_score', '')}")
    return "\n".join(lines).encode()
